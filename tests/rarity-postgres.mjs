// Run against an empty disposable database via PGlite. No production connection.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import roster from '../src/data/roster.js';
const db=new PGlite();
const file=path=>fs.readFile(new URL(path,import.meta.url),'utf8');
await db.exec(await file('./fixtures/rarity-db.sql'));
for(const {id} of roster)await db.query('insert into puppy_exchange.pup_exchange_transfer_policy values ($1,false,true,true,false)',[id]);
const owner=crypto.randomUUID(),staff=crypto.randomUUID(),player=crypto.randomUUID(),other=crypto.randomUUID();
for(const [account,id,role] of [[owner,player,'DEVELOPER'],[staff,other,'DEVELOPER']]){
 await db.query("insert into puppy_accounts.pup_accounts values ($1,$2,'active')",[account,id]);
 await db.query("insert into puppy_pupeye.pupeye_players values ($1,$2,'active')",[id,role]);
}
const save={stores:{puppy_clicker_save:{types:{unlocked_puppies:'string_set'},values:{unlocked_puppies:['classic','future_owned'],unknown_android_field:43}}}};
await db.query('insert into puppy_game.pup_account_saves values($1,$2,1,$3,now(),null)',[other,staff,save]);
for(const name of ['20261119080000_web_puppy_rarity.sql','20261119080100_rarity_exchange_gifts.sql'])
 await db.exec(await file('../supabase/migrations/'+name));
const scalar=async(sql,args=[])=>Object.values((await db.query(sql,args)).rows[0])[0];
const manage=(actor,body)=>scalar("select public.pup_rarity_manage($1,'update',$2)",[actor,body]);
const body={operationId:crypto.randomUUID(),puppyId:'midnight',version:1,rarity:'unobtainable',published:true,acquisition:'retired',reason:'Retirement'};
await assert.rejects(manage(owner,body),/OWNER_REQUIRED/);
await db.query('update puppy_rarity.config set owner_id=$1',[owner]);
await assert.rejects(manage(staff,body),/OWNER_REQUIRED/);
assert.equal((await manage(owner,body)).version,2);
assert.equal((await manage(owner,body)).version,2);
await assert.rejects(manage(owner,{...body,operationId:crypto.randomUUID()}),/VERSION_CONFLICT/);
await assert.rejects(manage(owner,{...body,reason:'different'}),/OPERATION_REUSED/);
await db.exec('set role authenticated');
await assert.rejects(manage(owner,body),/permission denied/);
await assert.rejects(db.exec("update puppy_rarity.catalog set published=false"),/permission denied/);
assert.equal((await scalar('select public.pup_rarity_public()')).length,32);
await db.exec('reset role');
await assert.rejects(db.exec("update puppy_game.pup_account_saves set save_data=jsonb_set(save_data,'{stores,puppy_clicker_save,values,unlocked_puppies}', '[\"classic\",\"midnight\"]')"),/PUPPY_RESTRICTED/);
await assert.rejects(db.exec(`update puppy_game.pup_account_saves set save_data=jsonb_set(save_data,'{stores,puppy_clicker_save,values,unlocked_puppies}', '["classic","new_unknown"]')`),/PUPPY_RESTRICTED/);
await db.exec("insert into puppy_exchange.pup_exchange_transfer_policy values ('new_puppy',false,true,true,false)");
const newRow=(await scalar("select public.pup_rarity_manage($1,'read','{}')",[owner])).rows.find(p=>p.puppy_id==='new_puppy');
assert.equal(newRow.version,0);
assert.equal((await manage(owner,{...body,operationId:crypto.randomUUID(),puppyId:'new_puppy',published:false,version:0})).version,1);
assert.equal((await scalar('select public.pup_rarity_public()')).length,32);
const offer=crypto.randomUUID();
await db.query("insert into puppy_exchange.pup_exchange_offers values($1,$2,$3,'gift',array['midnight'])",[offer,staff,staff]);
const accept=()=>scalar('select public.pup_exchange_complete($1,$2)',[offer,staff]);
await assert.rejects(accept(),/OWNER_REQUIRED/);
await db.query('update puppy_exchange.pup_exchange_offers set sender=$1',[owner]);
await assert.rejects(accept(),/OWNER_REQUIRED/);
const op=crypto.randomUUID();
const gift=actor=>scalar("select public.pup_rarity_gift($1,$2,'midnight',$3,'Owner gift')",[actor,other,op]);
await assert.rejects(gift(staff),/OWNER_REQUIRED/);
await assert.rejects(gift(owner),/OWNER_REQUIRED/);
await db.query('insert into puppy_exchange.pup_exchange_privileged_gifters values($1,true)',[owner]);
await db.exec("alter table puppy_rarity.history add constraint test_audit_failure check(action<>'gift')");
await assert.rejects(gift(owner),/test_audit_failure/);
assert.equal(await scalar('select revision::int from puppy_game.pup_account_saves'),1);
await db.exec('alter table puppy_rarity.history drop constraint test_audit_failure');
assert.equal((await gift(owner)).revision,2);
assert.equal((await gift(owner)).revision,2);
const saved=await scalar('select save_data from puppy_game.pup_account_saves');
assert.deepEqual(saved.stores.puppy_clicker_save.values,{unknown_android_field:43,unlocked_puppies:['classic','future_owned','midnight']});
assert.equal(await scalar('select count(*)::int from puppy_game.pup_system_notifications'),1);
assert.equal((await accept()).offer,offer);
assert.equal(await scalar("select count(*)::int from puppy_rarity.history where action='gift'"),2);
console.log('PostgreSQL rarity migration, roles, gift replay, ownership preservation and audit rollback passed.');
await db.close();
